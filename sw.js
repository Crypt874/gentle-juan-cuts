// Service worker: lets the site be installed like an app and keeps the pages available when the
// connection drops. Pages, scripts and styles always come from the network first (so updates show
// up right away) and fall back to the last saved copy. Firebase data is never cached here.
const CACHE = "gjc-shell-v1";

self.addEventListener("install", (e) => { self.skipWaiting(); });

self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;      // Firebase, fonts, CDNs: not touched
  if (url.pathname.includes("/__/")) return;             // Firebase Hosting reserved URLs
  e.respondWith(
    fetch(req)
      .then((res) => {
        if (res && res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
        }
        return res;
      })
      .catch(() => caches.match(req).then((hit) => hit || Response.error()))
  );
});
